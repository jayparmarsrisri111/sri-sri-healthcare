export function getCuratedPharmaciesByCity(cityName = '') {
  const norm = (cityName || '').toLowerCase().trim();
  if (!norm) return CURATED_PHARMACIES;
  const filtered = CURATED_PHARMACIES.filter(p =>
    p.city_or_village.toLowerCase().includes(norm) ||
    p.district.toLowerCase().includes(norm) ||
    p.name_gu.toLowerCase().includes(norm) ||
    p.name_en.toLowerCase().includes(norm) ||
    p.address_gu.toLowerCase().includes(norm)
  );
  return filtered.length > 0 ? filtered : CURATED_PHARMACIES;
}
